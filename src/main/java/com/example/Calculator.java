package com.example;

/**
 * A simple calculator class.
 */
public class Calculator {

    /**
     * Adds two integers.
     *
     * @param a The first integer to add
     * @param b The second integer to add
     * @return the sum of a and b
     */
    public int add(int a, int b) {
        return a + b;
    }
}
